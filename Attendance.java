    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       if (currentEmployee == null) {
            JOptionPane.showMessageDialog(this, "No employee logged in", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        currentEmployee.clockIn(); // Execute logic (file writing + duration calc)
        
        jTextField1.setText(getCurrentDateTime()); // Update GUI text
        updateButtonStates(); // Refresh buttons
        
        JOptionPane.showMessageDialog(this, "Clocked in successfully!");
    }//GEN-LAST:event_jButton1ActionPerformed

