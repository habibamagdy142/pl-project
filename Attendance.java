    private String getCurrentDateTime() {
        DateTimeFormatter formatter = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm");
        return LocalDateTime.now().format(formatter);
    }

    // Missing Method 2: Enable/Disable buttons based on status
    private void updateButtonStates() {
        if (currentEmployee == null) {
            jButton1.setEnabled(false); // Clock In
            jButton4.setEnabled(false); // Clock Out
            return;
        }

        // Check the status from the Employee object
        boolean clockedIn = currentEmployee.isClockedIn(); 
        
        jButton1.setEnabled(!clockedIn); // Disable Clock In if already in
        jButton4.setEnabled(clockedIn);  // Disable Clock Out if not in
    }

    


